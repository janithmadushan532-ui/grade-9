export function getPowerUpDuration(type: PowerUpType, level: number): number {
  const cfg = POWER_UPS[type];
  return cfg.baseDuration + (Math.max(1, level) - 1) * cfg.durationPerLevel;
}

export function getUpgradeCost(type: PowerUpType, currentLevel: number): number {
  const cfg = POWER_UPS[type];
  return Math.round(cfg.upgradeBaseCost * Math.pow(1.45, currentLevel - 1));
}
